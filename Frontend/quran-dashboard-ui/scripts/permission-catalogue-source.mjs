import { readFile } from 'node:fs/promises';

const constantsSource = new URL(
  '../../../Backend/application/QuranDashboard.Application.Abstractions/Security/Permissions/AbwabPermissions.cs',
  import.meta.url,
);
const catalogueSource = new URL(
  '../../../Backend/application/QuranDashboard.Application.Abstractions/Security/Permissions/AbwabPermissionCatalogue.cs',
  import.meta.url,
);

export const GENERATED_CODES_FILE = new URL(
  '../src/app/core/auth/permission-codes.generated.ts',
  import.meta.url,
);

const classBoundaryPattern = /public static class\s+/;
const constantPattern = /public const string (\w+)\s*=\s*"([^"]+)"\s*;/g;
const definitionPattern = /new\(\s*AbwabPermissions\.(\w+)\.(\w+)\s*,/g;
const definitionEntryPattern = /^\s*new\(/gm;

function parseConstants(source) {
  const constants = new Map();
  for (const section of source.split(classBoundaryPattern).slice(1)) {
    const className = section.match(/^(\w+)/)?.[1];
    if (className === undefined) {
      continue;
    }
    for (const [, memberName, code] of section.matchAll(constantPattern)) {
      constants.set(`${className}.${memberName}`, code);
    }
  }
  return constants;
}

function parseDefinitions(source, constants) {
  return [...source.matchAll(definitionPattern)].map(([, className, memberName]) => {
    const reference = `${className}.${memberName}`;
    const code = constants.get(reference);
    if (code === undefined) {
      throw new Error(
        `AbwabPermissionCatalogue references AbwabPermissions.${reference}, which AbwabPermissions.cs does not declare.`,
      );
    }
    return code;
  });
}

function camelCase(segment) {
  return segment.replace(/_(\w)/g, (_, letter) => letter.toUpperCase());
}

function groupedCodes(codes) {
  const groups = new Map();
  for (const code of codes) {
    const [, group, member] = code.split('.');
    const entries = groups.get(camelCase(group)) ?? new Map();
    entries.set(camelCase(member), code);
    groups.set(camelCase(group), entries);
  }
  return groups;
}

export function renderGeneratedCodes(codes) {
  const groups = [...groupedCodes(codes)].map(([group, entries]) => {
    const members = [...entries]
      .map(([member, code]) => `    ${member}: '${code}',`)
      .join('\n');
    return `  ${group}: {\n${members}\n  },`;
  });
  return [
    '/* eslint-disable */',
    '/* Code generated by scripts/generate-permission-codes.mjs DO NOT EDIT. */',
    '',
    'export const ABWAB_PERMISSION_CODES = {',
    ...groups,
    '} as const;',
    '',
  ].join('\n');
}

export async function readPermissionCatalogueSource() {
  const [constantsFile, catalogueFile] = await Promise.all([
    readFile(constantsSource, 'utf8'),
    readFile(catalogueSource, 'utf8'),
  ]);
  const constants = parseConstants(constantsFile);
  return {
    declaredCodes: [...constants.values()],
    catalogueCodes: parseDefinitions(catalogueFile, constants),
    catalogueEntryCount: [...catalogueFile.matchAll(definitionEntryPattern)].length,
  };
}
